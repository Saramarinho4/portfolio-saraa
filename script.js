(function () {
  var LANGS = ["pt", "en", "es"];
  var HTML_LANG = { pt: "pt-BR", en: "en", es: "es" };
  var KEY = "sara-lang";
  var WA = "https://wa.me/5514988033974?text=";

  function norm(v) {
    v = String(v || "").toLowerCase().slice(0, 2);
    return LANGS.indexOf(v) > -1 ? v : "";
  }
  function fromUrl() {
    try { return norm(new URLSearchParams(window.location.search).get("lang")); } catch (e) { return ""; }
  }
  function fromStore() {
    try { return norm(window.localStorage.getItem(KEY)); } catch (e) { return ""; }
  }
  function fromBrowser() {
    var l = "";
    try { l = String((navigator.languages && navigator.languages[0]) || navigator.language || "").toLowerCase(); } catch (e) {}
    if (l.indexOf("es") === 0) return "es";
    if (l.indexOf("en") === 0) return "en";
    return "pt";
  }
  function remember(lang) {
    try { window.localStorage.setItem(KEY, lang); } catch (e) {}
    try {
      var u = new URL(window.location.href);
      u.searchParams.set("lang", lang);
      window.history.replaceState(window.history.state, "", u.href);
    } catch (e) {}
  }

  function apply(lang) {
    var T = I18N[lang] || I18N.pt, P = I18N.pt;
    function t(k) { return T[k] != null ? T[k] : P[k]; }
    document.documentElement.setAttribute("lang", HTML_LANG[lang]);
    document.title = t("title");
    var meta = document.querySelector('meta[name="description"]');
    if (meta) meta.setAttribute("content", t("meta"));
    [].forEach.call(document.querySelectorAll("[data-i18n]"), function (n) {
      var v = t(n.getAttribute("data-i18n"));
      if (v != null) n.textContent = v;
    });
    [].forEach.call(document.querySelectorAll("[data-i18n-html]"), function (n) {
      var v = t(n.getAttribute("data-i18n-html"));
      if (v != null) n.innerHTML = v;
    });
    [].forEach.call(document.querySelectorAll("[data-i18n-attr]"), function (n) {
      n.getAttribute("data-i18n-attr").split(";").forEach(function (pair) {
        var i = pair.indexOf(":");
        if (i < 1) return;
        var v = t(pair.slice(i + 1).trim());
        if (v != null) n.setAttribute(pair.slice(0, i).trim(), v);
      });
    });
    [].forEach.call(document.querySelectorAll("[data-wa]"), function (a) {
      a.setAttribute("href", WA + encodeURIComponent(t("wa")));
    });
    [].forEach.call(document.querySelectorAll(".lang [data-lang]"), function (b) {
      b.setAttribute("aria-pressed", b.getAttribute("data-lang") === lang ? "true" : "false");
    });
    if (window.xProjText) window.xProjText(lang);
  }

  var urlLang = fromUrl(), stored = fromStore();
  var lang = urlLang || stored || fromBrowser();
  if (urlLang) {
    try { window.localStorage.setItem(KEY, urlLang); } catch (e) {}
  } else if (stored) {
    remember(stored);
  }
  apply(lang);

  [].forEach.call(document.querySelectorAll(".lang [data-lang]"), function (b) {
    b.addEventListener("click", function () {
      var l = b.getAttribute("data-lang");
      apply(l);
      remember(l);
    });
  });
})();
